import io
import json
from typing import List, Dict, Any
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle


def generate_interview_pdf(interview_data: Dict[str, Any]) -> bytes:
    """
    Renders structured interview questions and student profile into a clean, professional PDF.
    Returns bytes suitable for downloading.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#1e293b"),
        spaceAfter=6,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#64748b"),
        spaceAfter=12,
    )
    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#0f172a"),
        spaceBefore=10,
        spaceAfter=6,
    )
    question_title_style = ParagraphStyle(
        "QuestionTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#1e3a8a"),
    )
    meta_style = ParagraphStyle(
        "MetaText",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#475569"),
    )
    bullet_style = ParagraphStyle(
        "BulletText",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor("#334155"),
        leftIndent=12,
    )

    story = []

    # Title Banner
    story.append(Paragraph("AI Resume-Based Interview Questions", title_style))
    story.append(
        Paragraph(
            "Personalized Interview Evaluation Sheet & Question Bank generated by Google Gemini Agent",
            subtitle_style,
        )
    )
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563eb"), spaceAfter=12))

    # Candidate Profile Summary
    profile = interview_data.get("student_profile", {})
    name = profile.get("name", "Candidate")
    skills = profile.get("skills", [])
    projects = profile.get("projects", [])
    experience = profile.get("experience", [])

    profile_text = (
        f"<b>Candidate Name:</b> {name}<br/>"
        f"<b>Identified Skills:</b> {', '.join(skills) if skills else 'Not Provided'}<br/>"
        f"<b>Identified Projects:</b> {', '.join(projects) if projects else 'Not Provided'}<br/>"
        f"<b>Experience / Internships:</b> {', '.join(experience) if experience else 'None Listed'}"
    )
    story.append(Paragraph("Candidate Profile Summary", section_heading))
    story.append(Paragraph(profile_text, styles["Normal"]))
    story.append(Spacer(1, 14))

    # Questions Section
    questions: List[Dict[str, Any]] = interview_data.get("questions", [])
    story.append(Paragraph(f"Generated Interview Questions ({len(questions)} Total)", section_heading))
    story.append(Spacer(1, 6))

    category_badge_colors = {
        "Technical": colors.HexColor("#dbeafe"),
        "Project-Based": colors.HexColor("#fef3c7"),
        "Internship/Experience": colors.HexColor("#dcfce7"),
        "HR": colors.HexColor("#f3e8ff"),
        "Coding": colors.HexColor("#ffedd5"),
    }

    for q in questions:
        q_id = q.get("question_id", "")
        cat = q.get("category", "General")
        diff = q.get("difficulty", "Medium")
        q_text = q.get("question", "")
        related = q.get("related_skill", "")
        reason = q.get("reason", "")
        expected = q.get("expected_answer_points", [])

        # Question header block
        q_header = f"<b>Q{q_id}. [{cat}]</b> {q_text}"
        meta = f"Difficulty: <b>{diff}</b> | Focus Area: <b>{related}</b> | <i>Reason: {reason}</i>"

        story.append(Paragraph(q_header, question_title_style))
        story.append(Spacer(1, 2))
        story.append(Paragraph(meta, meta_style))
        story.append(Spacer(1, 4))

        if expected:
            story.append(Paragraph("<b>Expected Answer Criteria:</b>", meta_style))
            for pt in expected:
                story.append(Paragraph(f"• {pt}", bullet_style))

        story.append(Spacer(1, 10))
        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#e2e8f0"), spaceAfter=8))

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
